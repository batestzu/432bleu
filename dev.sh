#!/bin/bash
# Dev bench on Zoltan. Wraps docker compose with the dev env, the dev override
# and its own project name, so it can never be confused with the VPS stack.
#
#   ./dev.sh up            start the bench, reachable from Zoltan only:
#                            http://play.workadventure.localhost:8080
#   ./dev.sh phone         start (or switch) the bench so a phone on the same
#                          WiFi can open it. Prints the address to type.
#   ./dev.sh logs -f play  follow the front end / pusher
#   ./dev.sh ps | down | restart play | ...   any compose command
#
# `up` and `phone` switch between the two modes; switching recreates the
# containers whose addresses changed, which takes a couple of minutes.
#
# Phone mode uses <zoltan-ip>.nip.io names: nip.io is a public DNS service that
# answers any such name with the IP inside it, so nothing needs configuring on
# the phone. It is plain http, so the phone's browser will refuse the camera and
# microphone (they need https). Layout and touch testing work fine.
set -e
cd "$(dirname "${BASH_SOURCE[0]}")"
LAN_ENV=.env.dev.lan
ENVS=(--env-file .env.dev)
# What the venue room needs. Left out on purpose: boxoffice, postgres, umami,
# coturn, icecast, redisinsight.
CORE=(reverse-proxy redis messages back play map-storage maps icon uploader synapse oidc-server-mock)

write_lan_env() {
    local ip
    ip=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for (i = 1; i < NF; i++) if ($i == "src") print $(i + 1)}')
    [ -n "$ip" ] || { echo "No LAN address found: is Zoltan on a network?" >&2; exit 1; }
    local d="$ip.nip.io"
    cat > "$LAN_ENV" <<EOF
# Generated by ./dev.sh phone. Overrides .env.dev so every address uses Zoltan's
# LAN IP instead of *.localhost. Not in git: the IP changes with the network.
BASE_DOMAIN=$d
START_ROOM_URL=/_/global/maps.$d:8080/starter/map.json
OIDC_REDIRECT_URIS=http://play.$d:8080/openid-callback
MATRIX_PUBLIC_URI=http://matrix.$d:8080
EOF
    echo "$d"
}

case "${1:-}" in
    phone)
        shift
        domain=$(write_lan_env)
        docker compose "${ENVS[@]}" --env-file "$LAN_ENV" -p bleu-dev -f docker-compose.yaml -f docker-compose.dev.yaml up -d "$@" "${CORE[@]}"
        echo
        echo "On the phone (same WiFi), open:  http://play.$domain:8080"
        echo "The first load after a switch takes a minute or two."
        exit 0
        ;;
    up)
        shift
        rm -f "$LAN_ENV"
        exec docker compose "${ENVS[@]}" -p bleu-dev -f docker-compose.yaml -f docker-compose.dev.yaml up -d "$@" "${CORE[@]}"
        ;;
esac
# Any other command runs against whichever mode is current.
[ -f "$LAN_ENV" ] && ENVS+=(--env-file "$LAN_ENV")
exec docker compose "${ENVS[@]}" -p bleu-dev -f docker-compose.yaml -f docker-compose.dev.yaml "$@"
